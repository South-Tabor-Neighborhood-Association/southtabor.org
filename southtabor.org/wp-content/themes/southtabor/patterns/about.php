<h2 class="wp-block-heading">About South Tabor</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>South Tabor takes its name from Mt. Tabor Park, just to the north. It is a quiet, mostly residential neighborhood with beautiful gardens, schools, and a greenway that runs its full length east to west.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>STNA was formed in 1972 by parents from Kellogg, Youngson, and Atkinson elementary schools when the Mt. Hood Freeway threatened Southeast neighborhoods. Today we work to make Division and Powell safer, organize the garden tour, and build on what makes South Tabor a good place to live.</p>
